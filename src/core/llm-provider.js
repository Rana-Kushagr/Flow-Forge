/**
 * Flow-Forge LLM Provider
 * Supports Google Gemini API when GEMINI_API_KEY is configured,
 * with an intelligent rule-based / heuristic engine fallback for
 * zero-setup offline demos, rapid local testing, and instant client walkthroughs.
 */

export class LLMProvider {
  constructor(config = {}) {
    this.apiKey = config.apiKey || process.env.GEMINI_API_KEY || null;
    this.model = config.model || "gemini-1.5-flash";
  }

  /**
   * Request structured JSON response from Gemini or intelligent fallback
   */
  async completeJSON({ prompt, systemInstruction, fallbackHandler }) {
    if (this.apiKey) {
      try {
        const response = await this._callGemini(prompt, systemInstruction, true);
        return JSON.parse(response);
      } catch (err) {
        console.warn(`[LLMProvider] Gemini API call failed (${err.message}). Using intelligent engine fallback.`);
      }
    }

    if (fallbackHandler) {
      return fallbackHandler(prompt);
    }

    throw new Error("No API key provided and no fallback handler available.");
  }

  /**
   * Request text response
   */
  async completeText({ prompt, systemInstruction, fallbackHandler }) {
    if (this.apiKey) {
      try {
        return await this._callGemini(prompt, systemInstruction, false);
      } catch (err) {
        console.warn(`[LLMProvider] Gemini API call failed (${err.message}). Using intelligent engine fallback.`);
      }
    }

    if (fallbackHandler) {
      return fallbackHandler(prompt);
    }

    return "Automated response generated by Flow-Forge Core.";
  }

  async _callGemini(prompt, systemInstruction, isJson = false) {
    const url = `https://generativelanguage.googleapis.com/v1beta/models/${this.model}:generateContent?key=${this.apiKey}`;
    
    const body = {
      contents: [
        {
          role: "user",
          parts: [{ text: prompt }]
        }
      ],
      generationConfig: {
        temperature: 0.2,
        ...(isJson ? { responseMimeType: "application/json" } : {})
      }
    };

    if (systemInstruction) {
      body.systemInstruction = {
        parts: [{ text: systemInstruction }]
      };
    }

    const res = await fetch(url, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(body)
    });

    if (!res.ok) {
      const errText = await res.text();
      throw new Error(`Gemini HTTP ${res.status}: ${errText}`);
    }

    const data = await res.json();
    return data.candidates?.[0]?.content?.parts?.[0]?.text || "";
  }
}

export const defaultLLM = new LLMProvider();
